class Generator:

    currentMajor = None

    def LegalEncode(name : str) -> str: #AI generated function - to be rewriten
        n = int.from_bytes(name.encode(), 'big')
        if n == 0:
            return 'a'
        out = []
        while n:
            n, r = divmod(n, 26)
            out.append(chr(ord('a') + r))
        return ''.join(reversed(out))        

    def MacroArgumentPrepare(name : str, src : Passport):
        if src.datatype != "compute":Command(f"data modify storage szn:misc macro.{name} set from", src.datatype, src.object, src.field).auto()
        else:Command(f"data modify storage szn:misc macro.{name} set compute default float", src.field).auto()

    def MacroCallShortcut(name : str):
        Command(f"function support:{name}", "with storage szn:misc macro").auto()

    def GetReturnablePassport(n : node.Returnable) -> Passport:
        if isinstance(n, Passport): return n
        if isinstance(n, node.Content):
            return Passport(
                "Content",
                "string" if n.GetType() == "String" else "value",
                None,
                None,
                Provider("constant", [n.value]),
                constant=n.value
            )
        elif isinstance(n, node.Expression):
            if n.operation == "Concat" and n.baked == None:
                template = ""
                cntr = 0
                for p in [Generator.GetReturnablePassport(x) for x in n.operands]:
                    if p.constant == None:
                        print(p.field, p.object)
                        Generator.MacroArgumentPrepare(str(cntr), p)
                        template += f"$({cntr})"
                        cntr += 1
                    else : template += p.constant
                name = Generator.LegalEncode(template)
                SupportFunction(name, [f'$data modify storage szn:misc concat set value "{template}"'])
                Generator.MacroCallShortcut(name)

                return Passport(
                    "Expression",
                    "storage",
                    "szn:misc",
                    "concat",
                    Provider("storage", ["szn:misc", "concat"]),
                    constant=None
                )

            convert = {
                "Plus": "add",
                "Minus": "sub",
                "Times": "mul",
                "Divide": "div",
                "Power": "pow",
                "Sine": "sin",
                "Cosine" : "cos",
                "Negative": "negate"
                }

            return Passport(
                "Expression",
                "compute",
                "default",
                str(Provider(convert[n.operation], [Generator.GetReturnablePassport(o).provider for o in n.operands])),
                Provider(convert[n.operation], [Generator.GetReturnablePassport(o).provider for o in n.operands]),
                constant=n.baked
            )
        elif isinstance(n, node.Reference):
            return Passport(
                "Reference",
                "storage",
                n.name,
                "value",
                Provider("storage", [n.name, "value"]),
                constant=None
            )

    def ParseAST(AST : list[node.Node]):
        n = None
        for n in AST:
            if isinstance(n, node.FunctionDeclaration):
                Generator.currentMajor = Function(n.name, asociated=[n.name])
                Generator.ParseAST(n.body.members)
            elif isinstance(n, node.Assignment):
                tp = Generator.GetReturnablePassport(n.target)
                vp = Generator.GetReturnablePassport(n.value)


                if vp.datatype in ["block", "entity", "storage"]:Command("data modify", tp.datatype, tp.object, tp.field, "set from", vp.datatype, vp.object, vp.field).auto()
                else:Command("data modify", tp.datatype, tp.object, tp.field, "set", vp.datatype, vp.constant).auto()
                    

            elif isinstance(n, node.Direct):
                d = Generator.GetReturnablePassport(n.data)
                if d.constant != None : Command(d.constant).auto()
                else:
                    SupportFunction("direct", ["$$(data)"])
                    Generator.MacroArgumentPrepare("data", d)
                    Generator.MacroCallShortcut("direct")
            elif isinstance(n, node.AttributeModify):
                name = f"{n.attr}_{n.modifier}{"_remove" if n.value == False else ""}"
                ce = Generator.GetReturnablePassport(n.entity)
                cv = Generator.GetReturnablePassport(n.value)
                staticE = ce.constant != None
                staticV = cv != None and cv.constant != None
                fullyStatic = staticE and staticV

                if staticE: name += f"_{ce.constant}"
                elif staticV: name += f"_{cv.constant}"

                name = Generator.LegalEncode(name)

                if n.value == False:
                    if staticE:
                        Command(f"attribute {ce.constant} minecraft:{n.attr} modifier remove {n.modifier}").auto()
                    else:
                        SupportFunction(name, [f"$attribute $(e) minecraft:{n.attr} modifier remove {n.modifier}"])
                        Generator.MacroArgumentPrepare("e", ce)
                        Generator.MacroCallShortcut(name)
                else:
                    if fullyStatic:
                        Command(f"attribute {ce.constant} minecraft:{n.attr} modifier add {n.modifier} {cv.constant} add_value").auto()
                    elif staticE:
                        SupportFunction(name, [f"$attribute {ce.constant} minecraft:{n.attr} modifier add {n.modifier} $(v) add_value"])
                        Generator.MacroArgumentPrepare("v", cv)
                        Generator.MacroCallShortcut(name)
                    elif staticV:
                        SupportFunction(name, [f"$attribute $(e) minecraft:{n.attr} modifier add {n.modifier} {cv.constant} add_value"])
                        Generator.MacroArgumentPrepare("e", ce)
                        Generator.MacroCallShortcut(name)                    