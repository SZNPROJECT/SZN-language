class File: pass
class DataPiece: pass

class Central:
    f = []

    def GetProjectFiles(self): return self.f
    def GetAsociatedFunction(name : str): return [f for f in Central.f if name in f.asociated][0]

    def Build(name : str, dir : str):
        def BuildMeta():
            os.makedirs(dir+f"\\{name}\\", exist_ok=True)
            mcmeta = open(dir+f"\\{name}\\pack.mcmeta", "w")
            mcmeta.write('{"pack": {"description": "Auto generated by SZN.","min_format": 119,"max_format": 119}}')
            mcmeta.close()
        def CompileFunctions():
            for f in Central.f:
                p = dir+f"\\{name}\\data\\{f.namespace}\\function\\"
                os.makedirs(p, exist_ok=True)
                with open(p+f.name+".mcfunction", "w") as file: file.write(''.join([str(c) + "\n" for c in f.data]))
        BuildMeta()
        CompileFunctions()

class Function(File):
    current = None
    def __init__(self, name = "Name", data = None, namespace = "szn", asociated = []):
        self.name = name
        self.data = data if data != None else list()
        self.namespace = namespace
        Function.current = self
        Central.f.append(self)

class SupportFunction(Function):
    def __init__(self, name="Name", data=None):
        self.name = name
        self.data = data if data != None else list()
        self.namespace = "support"
        Central.f.append(self)

class Command:
    def __init__(self, *data : list[str]):
        self.data = data
        self.dynamic = False
        content = ""
        for p in data:
            if isinstance(p, node.External):
                op = Generator.GetReturnablePassport(p.obj)
                of = Generator.GetReturnablePassport(p.field)

                if not self.dynamic : self.dynamic = op.constant is None or of.constant is None

                

    def __str__(self):
        return " ".join([str(d) for d in self.data])

    def auto(self): 
        Function.current.data.append(self)



class Provider(DataPiece):
    def __init__(self, type : str, value : list["Provider"]):
        self.type = type
        self.value = value

    def __str__(self):
        pol = lambda x: f'"left": {x[0]}, "right": {x[1]}'
        una = lambda x: f'"input": {x[0]}'
        ser = lambda x: f'"inputs": [{', '.join(x)}]'
        convert = {
            "div" : pol,
            "sub" : pol,
            "sin" : una,
            "cos" : una,
            "constant" : lambda x: f'"value": {x[0]}',
            "storage": lambda x: f'"storage":"{x[0]}", "path":"{x[1]}"'
        }
        conv = lambda x: convert[self.type](x) if self.type in convert.keys() else ser(x)
        return f'{{"type": "{self.type}", {conv([str(p) for p in self.value])}}}'

